type mailCapture struct{ code string }

func (m *mailCapture) Send(_ context.Context, _ string, code string) error { m.code = code; return nil }
func database(t *testing.T) *store.Postgres {
	t.Helper()
	dsn := os.Getenv("NEXUS_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("NEXUS_TEST_DATABASE_URL not set; real PostgreSQL integration not executed")
	}
	db, e := sql.Open("pgx", dsn)
	if e != nil {
		t.Fatal(e)
	}
	db.SetMaxOpenConns(30)
	t.Cleanup(func() { db.Close() })
	ctx := context.Background()
	schema := strings.ToLower("test_" + strings.ReplaceAll(auth.Random(12), "-", "_"))
	// Random schema is generated by us, not user-controlled; pgx quotes identifier characters here.
	schema = strings.ReplaceAll(schema, "_", "x")
	if _, e = db.ExecContext(ctx, `CREATE SCHEMA "`+schema+`"`); e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() { _, _ = db.Exec(`DROP SCHEMA "` + schema + `" CASCADE`) })
	db.Close()
	sep := "?"
	if strings.Contains(dsn, "?") {
		sep = "&"
	}
	db, e = sql.Open("pgx", dsn+sep+"search_path="+schema)
	if e != nil {
		t.Fatal(e)
	}
	db.SetMaxOpenConns(30)
	up, e := os.ReadFile("../../migrations/000001_init.up.sql")
	if e != nil {
		t.Fatal(e)
	}
	if _, e = db.Exec(string(up)); e != nil {
		t.Fatal(e)
	}
	activity, e := os.ReadFile("../../migrations/000002_activity.up.sql")
	if e != nil {
		t.Fatal(e)
	}
	if _, e = db.Exec(string(activity)); e != nil {
		t.Fatal(e)
	}
	metadata, e := os.ReadFile("../../migrations/000003_source_metadata.up.sql")
	if e != nil {
		t.Fatal(e)
	}
	if _, e = db.Exec(string(metadata)); e != nil {
		t.Fatal(e)
	}
	return &store.Postgres{DB: db, EncryptionKey: []byte(strings.Repeat("e", 32)), LookupKey: []byte(strings.Repeat("l", 32))}
}
func TestPostgresAuthConcurrencyAndSocial(t *testing.T) {
	p := database(t)
	ctx := context.Background()
	now := time.Now().UTC()
	m := &mailCapture{}
	s := &auth.Service{Store: p, Mail: m, LookupKey: p.LookupKey, Now: func() time.Time { return now }, Tokens: auth.Tokens{Key: []byte(strings.Repeat("j", 32)), Now: func() time.Time { return now }}}
	phone, device := "+959123456789", "device-012345678901"
	if e := s.Register(ctx, phone, device, "owner@example.com"); e != nil {
		t.Fatal(e)
	}
	if e := s.Register(ctx, "+959123456788", device, "owner@example.com"); !errors.Is(e, core.ErrConflict) {
		t.Fatal(e)
	}
	if _, e := s.DeviceLogin(ctx, phone, device); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	if e := s.EmailVerify(ctx, phone, "owner@example.com"); e != nil {
		t.Fatal(e)
	}
	if e := s.EmailVerify(ctx, phone, "owner@example.com"); !errors.Is(e, core.ErrLimited) {
		t.Fatal(e)
	}
	parts := strings.Split(m.code, ".")
	if _, e := s.Confirm(ctx, parts[0]+"."+strings.Repeat("x", 43), device); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	var wins atomic.Int32
	var wg sync.WaitGroup
	var pair auth.Pair
	var mu sync.Mutex
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			v, e := s.Confirm(ctx, m.code, device)
			if e == nil {
				wins.Add(1)
				mu.Lock()
				pair = auth.ExternalRefresh(v, s.Tokens)
				mu.Unlock()
			} else if !errors.Is(e, core.ErrUnauthorized) {
				t.Error(e)
			}
		}()
	}
	wg.Wait()
	if wins.Load() != 1 {
		t.Fatal("OTP winners", wins.Load())
	}
	u, sid, e := s.Authenticate(ctx, pair.JWT)
	if e != nil {
		t.Fatal(e)
	}
	name, bio := "Sophie Jap", "Editorial films"
	profile, e := p.Profile(ctx, u.ID, &core.ProfilePatch{Name: &name, Bio: &bio})
	if e != nil || profile.Email != "owner@example.com" {
		t.Fatal(profile, e)
	}
	var cipher []byte
	if e = p.DB.QueryRow(`SELECT email_cipher FROM users WHERE id=$1`, u.ID).Scan(&cipher); e != nil {
		t.Fatal(e)
	}
	if strings.Contains(string(cipher), "owner") {
		t.Fatal("plaintext PII")
	}
	if _, e = s.DeviceLogin(ctx, phone, device); e != nil {
		t.Fatal(e)
	}
	r, e := s.Refresh(ctx, pair.Refresh)
	if e != nil {
		t.Fatal(e)
	}
	r = auth.ExternalRefresh(r, s.Tokens)
	if _, e = s.Refresh(ctx, pair.Refresh); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	if ok, e := p.Active(ctx, u.ID, sid, now); e != nil || ok {
		t.Fatal("replay did not revoke", ok, e)
	}
	if _, e = s.Refresh(ctx, r.Refresh); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	peer := core.User{ID: "peer", Phone: "+959123456787", Email: "peer@example.com", DeviceHash: "peer-device"}
	if e = p.Register(ctx, peer); e != nil {
		t.Fatal(e)
	}
	outsider := core.User{ID: "outsider", Phone: "+959123456786", Email: "outsider@example.com", DeviceHash: "out-device"}
	if e = p.Register(ctx, outsider); e != nil {
		t.Fatal(e)
	}
	thread, e := p.Create(ctx, u.ID, core.Item{Kind: "thread"}, []string{peer.ID})
	if e != nil {
		t.Fatal(e)
	}
	msg, e := p.Create(ctx, peer.ID, core.Item{Kind: "message", ParentID: thread.ID, Body: "Hello"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = p.Get(ctx, outsider.ID, "thread", thread.ID); !errors.Is(e, core.ErrNotFound) {
		t.Fatal("private thread leak", e)
	}
	items, e := p.List(ctx, core.Query{Kind: "message", UserID: outsider.ID, Limit: 10})
	if e != nil || len(items) != 0 {
		t.Fatal("private message leak", items, e)
	}
	if _, e = p.Create(ctx, outsider.ID, core.Item{Kind: "message", ParentID: thread.ID, Body: "intrude"}, nil); !errors.Is(e, core.ErrForbidden) {
		t.Fatal(e)
	}
	if e = p.Membership(ctx, peer.ID, "thread", thread.ID, false); e != nil {
		t.Fatal(e)
	}
	if _, e = p.Get(ctx, peer.ID, "message", msg.ID); !errors.Is(e, core.ErrNotFound) {
		t.Fatal("left member access", e)
	}
	if e = p.Membership(ctx, outsider.ID, "thread", thread.ID, true); !errors.Is(e, core.ErrForbidden) {
		t.Fatal(e)
	}
	group, e := p.Create(ctx, u.ID, core.Item{Kind: "group", Name: "Inya Lake Runners", Visibility: "private"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	post, e := p.Create(ctx, u.ID, core.Item{Kind: "post", ParentID: group.ID, Body: "Saturday route"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	comment, e := p.Create(ctx, u.ID, core.Item{Kind: "comment", ParentID: post.ID, Body: "Meet at north gate"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	for kind, id := range map[string]int64{"post": post.ID, "comment": comment.ID} {
		if _, e = p.Get(ctx, outsider.ID, kind, id); !errors.Is(e, core.ErrNotFound) {
			t.Fatal("nested group leak", kind, e)
		}
	}
	if e = p.Relation(ctx, outsider.ID, "like", comment.ID, true); !errors.Is(e, core.ErrNotFound) {
		t.Fatal(e)
	}
	public, e := p.Create(ctx, u.ID, core.Item{Kind: "group", Name: "Public runners"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	if e = p.Membership(ctx, peer.ID, "group", public.ID, true); e != nil {
		t.Fatal(e)
	}
	if _, e = p.List(ctx, core.Query{Kind: "member", UserID: peer.ID, ParentID: public.ID, Limit: 10}); e != nil {
		t.Fatal(e)
	}
	if _, e = p.List(ctx, core.Query{Kind: "member", UserID: outsider.ID, ParentID: public.ID, Limit: 10}); !errors.Is(e, core.ErrForbidden) {
		t.Fatal(e)
	}
	if e = p.Membership(ctx, u.ID, "group", public.ID, false); !errors.Is(e, core.ErrConflict) {
		t.Fatal(e)
	}
	shop, e := p.Create(ctx, u.ID, core.Item{Kind: "shop", Name: "Shwe Kyaung Coffee"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = p.Create(ctx, peer.ID, core.Item{Kind: "product", ParentID: shop.ID, Name: "Mohinga", Price: 2500, Currency: "MMK"}, nil); !errors.Is(e, core.ErrForbidden) {
		t.Fatal(e)
	}
	product, e := p.Create(ctx, u.ID, core.Item{Kind: "product", ParentID: shop.ID, Name: "Mohinga", Price: 2500, Currency: "MMK"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	for _, kind := range []string{"like", "save", "follow"} {
		if e = p.Relation(ctx, peer.ID, kind, product.ID, true); e != nil {
			t.Fatal(e)
		}
		if e = p.Relation(ctx, peer.ID, kind, product.ID, false); e != nil {
			t.Fatal(e)
		}
	}
	for i := 0; i < 3; i++ {
		if _, e = p.Create(ctx, u.ID, core.Item{Kind: "post", Body: fmt.Sprintf("post %d", i)}, nil); e != nil {
			t.Fatal(e)
		}
	}
	list, e := p.List(ctx, core.Query{Kind: "post", UserID: u.ID, Limit: 2})
	if e != nil || len(list) != 2 {
		t.Fatal(list, e)
	}
	next, e := p.List(ctx, core.Query{Kind: "post", UserID: u.ID, Limit: 2, Before: list[1].ID})
	if e != nil || len(next) == 0 || next[0].ID >= list[1].ID {
		t.Fatal(next, e)
	}
	if _, e = p.List(ctx, core.Query{Kind: "people", UserID: u.ID, Limit: 10}); e != nil {
		t.Fatal(e)
	}
	// Persistent wrong-code attempts, expiry, cancellation and session expiry.
	now = now.Add(time.Minute)
	if e = s.EmailVerify(ctx, phone, "owner@example.com"); e != nil {
		t.Fatal(e)
	}
	parts = strings.Split(m.code, ".")
	for i := 0; i < 5; i++ {
		_, _ = s.Confirm(ctx, parts[0]+"."+strings.Repeat("z", 43), device)
	}
	if _, e = s.Confirm(ctx, m.code, device); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal("lockout failed", e)
	}
	now = now.Add(time.Minute)
	_ = s.EmailVerify(ctx, phone, "owner@example.com")
	now = now.Add(11 * time.Minute)
	if _, e = s.Confirm(ctx, m.code, device); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal("expiry failed", e)
	}
	_ = s.EmailVerify(ctx, phone, "owner@example.com")
	if e = p.CancelChallenge(ctx, auth.Digest(strings.Split(m.code, ".")[0])); e != nil {
		t.Fatal(e)
	}
	if _, e = s.Confirm(ctx, m.code, device); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	if e = p.DeleteUser(ctx, u.ID); e != nil {
		t.Fatal(e)
	}
	if _, e = p.Profile(ctx, u.ID, nil); !errors.Is(e, core.ErrNotFound) {
		t.Fatal(e)
	}
	down, e := os.ReadFile("../../migrations/000001_init.down.sql")
	if e != nil {
		t.Fatal(e)
	}
	activityDown, _ := os.ReadFile("../../migrations/000002_activity.down.sql")
	if _, e = p.DB.Exec(string(activityDown)); e != nil {
		t.Fatal(e)
	}
	if _, e = p.DB.Exec(string(down)); e != nil {
		t.Fatal("down migration", e)
	}
	up, _ := os.ReadFile("../../migrations/000001_init.up.sql")
	if _, e = p.DB.Exec(string(up)); e != nil {
		t.Fatal("up migration after down", e)
	}
}

func TestPostgresHTTPJourney(t *testing.T) {
	p := database(t)
	ctx := context.Background()
	m := &mailCapture{}
	s := &auth.Service{Store: p, Mail: m, LookupKey: p.LookupKey, Now: time.Now, Tokens: auth.Tokens{Key: []byte(strings.Repeat("j", 32)), Now: time.Now}}
	a := &httpapi.API{Auth: s, Social: p, Logger: slog.New(slog.NewTextHandler(io.Discard, nil))}
	h := a.Handler()
	call := func(path, body string, status int) *httptest.ResponseRecorder {
		t.Helper()
		r := httptest.NewRequest("POST", "/api/v1/"+path, strings.NewReader(body))
		r.Header.Set("Content-Type", "application/json")
		w := httptest.NewRecorder()
		h.ServeHTTP(w, r)
		if w.Code != status {
			t.Fatalf("%s %d %s", path, w.Code, w.Body.String())
		}
		return w
	}
	call("auth/register", `{"phone_number":"+959123456789","email":"owner@example.com","device_id":"original-device-0123456789"}`, 202)
	call("auth/device-login", `{"phone_number":"+959123456789","device_id":"original-device-0123456789"}`, 202)
	call("auth/email-verify", `{"phone_number":"+959123456789","email":"owner@example.com"}`, 202)
	call("auth/otp/confirm", `{"otp":"`+m.code+`","device_id":"replacement-device-0123456789"}`, 200)
	w := call("auth/device-login", `{"phone_number":"+959123456789","device_id":"replacement-device-0123456789"}`, 200)
	var pair auth.Pair
	_ = json.Unmarshal(w.Body.Bytes(), &pair)
	r := httptest.NewRequest("POST", "/api/v1/feed", strings.NewReader(`{"body":"persistent HTTP post"}`))
	r.Header.Set("Content-Type", "application/json")
	r.Header.Set("Authorization", "Bearer "+pair.JWT)
	w = httptest.NewRecorder()
	h.ServeHTTP(w, r)
	if w.Code != 201 {
		t.Fatal(w.Code, w.Body.String())
	}
	var wins atomic.Int32
	var wg sync.WaitGroup
	var winner auth.Pair
	var winnerMu sync.Mutex
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if v, e := s.Refresh(ctx, pair.Refresh); e == nil {
				wins.Add(1)
				winnerMu.Lock()
				winner = auth.ExternalRefresh(v, s.Tokens)
				winnerMu.Unlock()
			} else if !errors.Is(e, core.ErrUnauthorized) {
				t.Error(e)
			}
		}()
	}
	wg.Wait()
	if wins.Load() != 1 {
		t.Fatal("real refresh winners", wins.Load())
	}
	if _, _, e := s.Authenticate(ctx, winner.JWT); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal("concurrent replay must revoke winner family", e)
	}
	if _, e := s.Refresh(ctx, winner.Refresh); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal("winner refresh remains usable after replay", e)
	}
	// Real shared limiter must permit exactly one reservation under concurrent requests.
	wins.Store(0)
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if e := p.Limit(ctx, "concurrent-reservation", 1, time.Minute, time.Now()); e == nil {
				wins.Add(1)
			} else if !errors.Is(e, core.ErrLimited) {
				t.Error(e)
			}
		}()
	}
	wg.Wait()
	if wins.Load() != 1 {
		t.Fatal("real rate limiter winners", wins.Load())
	}
}

func TestPostgresValidationAndAuthorization(t *testing.T) {
	p := database(t)
	ctx := context.Background()
	u := core.User{ID: "owner", Phone: "+959123456789", Email: "owner@example.com", DeviceHash: "device"}
	if e := p.Register(ctx, u); e != nil {
		t.Fatal(e)
	}
	for _, i := range []core.Item{{Kind: "invalid"}, {Kind: "post"}, {Kind: "group"}, {Kind: "post", Body: "x", Visibility: "invalid"}, {Kind: "product", Name: "x", Currency: "EUR"}, {Kind: "comment", Body: "x"}, {Kind: "message", Body: "x"}, {Kind: "shop", Name: "x", ParentID: 1}, {Kind: "post", Body: strings.Repeat("x", 5001)}, {Kind: "post", Body: "x", Price: -1}} {
		if _, e := p.Create(ctx, u.ID, i, nil); !errors.Is(e, core.ErrInvalid) {
			t.Fatal(i, e)
		}
	}
	if _, e := p.Create(ctx, u.ID, core.Item{Kind: "thread"}, nil); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if _, e := p.Create(ctx, u.ID, core.Item{Kind: "group", Name: "x"}, []string{"unexpected"}); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	longName := strings.Repeat("x", 121)
	if _, e := p.Profile(ctx, u.ID, &core.ProfilePatch{Name: &longName}); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if _, e := p.List(ctx, core.Query{Limit: 0}); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if e := p.Relation(ctx, u.ID, "unexpected", 1, true); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if e := p.Membership(ctx, u.ID, "group", 999, false); !errors.Is(e, core.ErrNotFound) {
		t.Fatal(e)
	}
	if _, e := p.Create(ctx, u.ID, core.Item{Kind: "product", ParentID: 999, Name: "x", Currency: "MMK"}, nil); !errors.Is(e, core.ErrNotFound) {
		t.Fatal(e)
	}
	shop, e := p.Create(ctx, u.ID, core.Item{Kind: "shop", Name: "x"}, nil)
	if e != nil {
		t.Fatal(e)
	}
	if _, e = p.Create(ctx, u.ID, core.Item{Kind: "message", ParentID: shop.ID, Body: "x"}, nil); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if _, e = p.Grant(ctx, core.Grant{Mode: "invalid"}); !errors.Is(e, core.ErrInvalid) {
		t.Fatal(e)
	}
	if _, e = p.Grant(ctx, core.Grant{Mode: "otp", Selector: "missing"}); !errors.Is(e, core.ErrUnauthorized) {
		t.Fatal(e)
	}
	if e = p.Revoke(ctx, u.ID, "missing"); e != nil {
		t.Fatal(e)
	}
}
